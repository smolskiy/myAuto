/** Порядок символов в диапазонах ISO 3780 (буквы I, O, Q в VIN не бывают). */
const SECOND_CHAR_ORDER = 'ABCDEFGHJKLMNPRSTUVWXYZ1234567890'

function expandRegions(ranges: [string, string][]): Record<string, string> {
  const out: Record<string, string> = {}
  for (const [chars, region] of ranges) for (const c of chars) out[c] = region
  return out
}

