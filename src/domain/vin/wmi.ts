/** Страна по первым двум символам VIN; undefined — код не распределён. */
export function countryByCode(first: string, second: string): string | undefined {
  const pos = SECOND_CHAR_ORDER.indexOf(second)
  for (const [f, range, country] of COUNTRY_RANGES) {
    if (f !== first) continue
    if (range === '') return country
    const from = SECOND_CHAR_ORDER.indexOf(range[0]!)
    const to = SECOND_CHAR_ORDER.indexOf(range[1]!)
    if (pos >= from && pos <= to) return country
  }
  return undefined
}
